CREATE TABLE public.empresa(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 razon_social varchar(180) NOT NULL, nombre_comercial varchar(150) NOT NULL,
 slug varchar(80) NOT NULL CONSTRAINT uq_empresa_slug UNIQUE,
 nit varchar(40), correo_contacto varchar(150), telefono varchar(35),
 estado boolean NOT NULL DEFAULT true, fecha_creacion timestamptz NOT NULL DEFAULT now(),
 fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT ck_empresa_slug CHECK(slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 CONSTRAINT ck_empresa_razon CHECK(length(btrim(razon_social))>0),
 CONSTRAINT ck_empresa_nombre CHECK(length(btrim(nombre_comercial))>0));
CREATE TABLE public.plan_saas(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(35) NOT NULL CONSTRAINT uq_plan_saas_codigo UNIQUE,
 nombre varchar(100) NOT NULL, descripcion text,
 max_sucursales_activas integer NOT NULL CHECK(max_sucursales_activas BETWEEN 1 AND 1000),
 permite_productos boolean NOT NULL DEFAULT true, permite_ventas boolean NOT NULL DEFAULT true,
 permite_reservas boolean NOT NULL DEFAULT true, permite_offline boolean NOT NULL DEFAULT true,
 permite_reportes_convencionales boolean NOT NULL DEFAULT true,
 permite_reportes_ia boolean NOT NULL DEFAULT false, estado boolean NOT NULL DEFAULT true,
 fecha_creacion timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT ck_plan_codigo CHECK(codigo ~ '^[A-Z][A-Z0-9_]*$'));
CREATE TABLE public.suscripcion(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id bigint NOT NULL,
 plan_saas_id bigint NOT NULL, fecha_inicio date NOT NULL, fecha_vencimiento date NOT NULL,
 estado varchar(20) NOT NULL DEFAULT 'PENDIENTE', observacion text,
 fecha_creacion timestamptz NOT NULL DEFAULT now(), fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT fk_suscripcion_empresa FOREIGN KEY(empresa_id) REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_suscripcion_plan FOREIGN KEY(plan_saas_id) REFERENCES public.plan_saas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT ck_suscripcion_fecha CHECK(fecha_vencimiento>=fecha_inicio),
 CONSTRAINT ck_suscripcion_estado CHECK(estado IN('PENDIENTE','ACTIVA','SUSPENDIDA','VENCIDA','CANCELADA')));
CREATE UNIQUE INDEX uq_suscripcion_empresa_activa ON public.suscripcion(empresa_id) WHERE estado='ACTIVA';
CREATE INDEX idx_suscripcion_empresa_vencimiento ON public.suscripcion(empresa_id,fecha_vencimiento DESC);
CREATE TABLE public.usuario_empresa(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id bigint NOT NULL,
 empresa_id bigint NOT NULL, rol_id bigint NOT NULL, estado boolean NOT NULL DEFAULT true,
 fecha_asignacion timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT fk_usuario_empresa_usuario FOREIGN KEY(usuario_id) REFERENCES public.usuario(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_usuario_empresa_empresa FOREIGN KEY(empresa_id) REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_usuario_empresa_rol FOREIGN KEY(rol_id) REFERENCES public.rol(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT uq_usuario_empresa UNIQUE(usuario_id,empresa_id));
CREATE INDEX idx_usuario_empresa_empresa_rol ON public.usuario_empresa(empresa_id,rol_id) WHERE estado;
CREATE TABLE public.empresa_configuracion(
 empresa_id bigint PRIMARY KEY REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE CASCADE,
 logo_url text, color_primario varchar(7) NOT NULL DEFAULT '#111827',
 color_secundario varchar(7) NOT NULL DEFAULT '#FFFFFF', moneda varchar(3) NOT NULL DEFAULT 'BOB',
 zona_horaria varchar(80) NOT NULL DEFAULT 'America/La_Paz',
 configuracion_extra jsonb NOT NULL DEFAULT '{}'::jsonb, fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
 CHECK(color_primario ~ '^#[0-9A-Fa-f]{6}$'), CHECK(color_secundario ~ '^#[0-9A-Fa-f]{6}$'),
 CHECK(jsonb_typeof(configuracion_extra)='object'));

