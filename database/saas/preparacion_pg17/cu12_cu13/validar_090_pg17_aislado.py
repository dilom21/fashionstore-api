def ejecutar_pruebas(c) -> None:
    # CU12 confirmar: estado y stock intactos; tenant ajeno no visible.
    actor(c, 1, 101)
    c.execute("CALL public.sp_confirmar_reserva_tenant(1,5002,101)")
    require(uno(c, "SELECT estado FROM reserva WHERE id=5002") == "CONFIRMADA",
            "CU12 no confirmó la reserva PENDIENTE")
    require(uno(c, "SELECT stock_reservado FROM inventario WHERE id=1001") == 3,
            "CU12 confirmar alteró stock_reservado")
    try:
        c.execute("CALL public.sp_confirmar_reserva_tenant(1,5004,101)")
    except psycopg.Error as exc:
        require(exc.sqlstate == "P0002", "CU12 reserva ajena no devolvió P0002")
    else:
        raise AssertionError("CU12 confirmó una reserva de otra empresa")
    actor(c, 1, 103)
    try:
        c.execute("CALL public.sp_confirmar_reserva_tenant(1,5002,103)")
    except psycopg.Error as exc:
        require(exc.sqlstate == "42501",
                "CU12 no bloqueó confirmación por CAJERO")
    else:
        raise AssertionError("CU12 permitió confirmar a un CAJERO")

    # CU13 venta directa: precio/total del servidor, stock intacto.
    actor(c, 1, 102)
    venta_directa = crear_venta(c, 1, 102, [{"inventario_id": 1001, "cantidad": 2}])
    fila = c.execute(
        "SELECT empresa_id,canal,estado,total FROM venta WHERE id=%s",
        (venta_directa,),
    ).fetchone()
    require(fila == (1, "PRESENCIAL", "PENDIENTE", 100),
            "CU13 venta directa con total/estado incorrectos")
    require(uno(c, "SELECT stock_actual FROM inventario WHERE id=1001") == 5,
            "CU13 venta directa descontó stock antes del pago")

    # Encargado A no puede vender inventario de otra sucursal.
    actor(c, 1, 102)
    try:
        crear_venta(c, 1, 102, [{"inventario_id": 1002, "cantidad": 1}])
    except psycopg.Error as exc:
        require(exc.sqlstate == "42501", "CU13 no bloqueó sucursal ajena")
    else:
        raise AssertionError("CU13 permitió venta en sucursal ajena")

    # Venta desde reserva CONFIRMADA y duplicado bloqueado.
    actor(c, 1, 101)
    venta_reserva = crear_venta(
        c, 1, 101, [{"inventario_id": 1001, "cantidad": 2}], reserva_id=5001
    )
    require(uno(c, "SELECT reserva_id FROM venta WHERE id=%s", (venta_reserva,)) == 5001,
            "CU13 no asoció la reserva")
    try:
        crear_venta(c, 1, 101, [{"inventario_id": 1001, "cantidad": 1}], reserva_id=5001)
    except psycopg.Error as exc:
        require(exc.sqlstate == "23505", "CU13 no bloqueó venta duplicada")
    else:
        raise AssertionError("CU13 aceptó dos ventas para la misma reserva")

    # Pago desde reserva: consume reservado, descuenta stock y atiende reserva.
    actor(c, 1, 101)
    pago_id = pagar(c, 1, 101, venta_reserva)
    require(uno(c, "SELECT estado FROM pago WHERE id=%s", (pago_id,)) == "APROBADO",
            "CU13 pago no quedó APROBADO")
    require(uno(c, "SELECT estado FROM venta WHERE id=%s", (venta_reserva,)) == "COMPLETADA",
            "CU13 venta no quedó COMPLETADA")
    require(uno(c, "SELECT estado FROM reserva WHERE id=5001") == "ATENDIDA",
            "CU13 no marcó la reserva ATENDIDA")
    require((uno(c, "SELECT stock_actual FROM inventario WHERE id=1001"),
             uno(c, "SELECT stock_reservado FROM inventario WHERE id=1001")) == (3, 1),
            "CU13 pago dejó stock incorrecto")
    try:
        pagar(c, 1, 101, venta_reserva)
    except psycopg.Error as exc:
        require(exc.sqlstate in ("23514", "P0002"),
                "CU13 pago duplicado devolvió SQLSTATE inesperado")
    else:
        raise AssertionError("CU13 aceptó pago duplicado")
    require(uno(c, "SELECT count(*) FROM pago WHERE venta_id=%s", (venta_reserva,)) == 1,
            "CU13 duplicó el pago")

    # Pago directo y stock insuficiente.
    actor(c, 1, 101)
    pagar(c, 1, 101, venta_directa)
    require(uno(c, "SELECT stock_actual FROM inventario WHERE id=1001") == 1,
            "CU13 pago directo no descontó stock")
    try:
        crear_venta(c, 1, 101, [{"inventario_id": 1003, "cantidad": 2}])
    except psycopg.Error as exc:
        require(exc.sqlstate == "23514", "CU13 no bloqueó stock insuficiente")
    else:
        raise AssertionError("CU13 aceptó stock insuficiente")
    require(uno(c, "SELECT count(*) FROM venta WHERE sucursal_id=1") == 2,
            "CU13 dejó una venta parcial tras fallo")

    # Pago con stock insuficiente: rollback total del pago APROBADO.
    actor(c, 1, 101)
    venta_sin_stock = crear_venta(
        c, 1, 101, [{"inventario_id": 1003, "cantidad": 1}]
    )
    c.execute("UPDATE inventario SET stock_actual=0 WHERE id=1003")
    try:
        pagar(c, 1, 101, venta_sin_stock)
    except psycopg.Error as exc:
        require(exc.sqlstate == "23514",
                "CU13 pago sin stock no devolvió 23514")
    else:
        raise AssertionError("CU13 confirmó pago sin stock")
    require(uno(c, "SELECT count(*) FROM pago WHERE venta_id=%s",
                (venta_sin_stock,)) == 0,
            "CU13 dejó pago APROBADO tras fallo de stock")
    require(uno(c, "SELECT estado FROM venta WHERE id=%s",
                (venta_sin_stock,)) == "PENDIENTE",
            "CU13 completó venta sin stock")
    c.execute("UPDATE inventario SET stock_actual=1 WHERE id=1003")

    # Metodo de pago fuera del CHECK real.
    actor(c, 1, 101)
    try:
        pagar(c, 1, 101, venta_sin_stock, metodo="BITCOIN")
    except psycopg.Error as exc:
        require(exc.sqlstate == "22023",
                "CU13 no rechazó metodo de pago inválido")
    else:
        raise AssertionError("CU13 aceptó metodo de pago inválido")

    # Encargado B no puede pagar venta de A.
    actor(c, 2, 201)
    try:
        pagar(c, 2, 201, venta_directa)
    except psycopg.Error as exc:
        require(exc.sqlstate == "P0002", "CU13 no aisló venta de otra empresa")
    else:
        raise AssertionError("CU13 permitió pagar venta de otra empresa")

    # Concurrencia: dos pagos simultáneos de la misma venta, uno gana.
    actor(c, 1, 101)
    venta_carrera = crear_venta(
        c, 1, 101, [{"inventario_id": 1002, "cantidad": 1}]
    )
    barrier = threading.Barrier(2)

    def intentar_pago(_):
        with conectar("postgres", PASSWORD) as conn:
            actor(conn, 1, 101)
            barrier.wait(timeout=10)
            try:
                pagar(conn, 1, 101, venta_carrera)
                return "OK"
            except psycopg.Error as exc:
                require(exc.sqlstate in ("23514", "P0002"),
                        "carrera de pago devolvió SQLSTATE inesperado")
                return "RECHAZADO"

    with ThreadPoolExecutor(max_workers=2) as pool:
        resultados = list(pool.map(intentar_pago, (1, 2)))
    require(sorted(resultados) == ["OK", "RECHAZADO"],
            "CU13 no serializó pagos concurrentes")
    require(uno(c, "SELECT count(*) FROM pago WHERE venta_id=%s", (venta_carrera,)) == 1,
            "CU13 dejó pagos duplicados en concurrencia")
    require(uno(c, "SELECT stock_actual FROM inventario WHERE id=1002") == 4,
            "CU13 descontó stock dos veces en concurrencia")

    # ADMINISTRADOR sin empleado: alcance empresarial como en el primer parcial.
    # ENCARGADO_SUCURSAL sin empleado: sigue bloqueado.
    actor(c, 3, 302)
    try:
        c.execute("CALL public.sp_confirmar_reserva_tenant(3,6002,302)")
    except psycopg.Error as exc:
        require(exc.sqlstate == "42501",
                "ENCARGADO sin empleado confirmó una reserva")
    else:
        raise AssertionError("ENCARGADO sin empleado confirmó una reserva")
    try:
        crear_venta(c, 3, 302, [{"inventario_id": 3001, "cantidad": 1}])
    except psycopg.Error as exc:
        require(exc.sqlstate == "42501",
                "ENCARGADO sin empleado creó una venta")
    else:
        raise AssertionError("ENCARGADO sin empleado creó una venta")

    actor(c, 3, 301)
    c.execute("CALL public.sp_confirmar_reserva_tenant(3,6001,301)")
    require(uno(c, "SELECT estado FROM reserva WHERE id=6001") == "CONFIRMADA",
            "ADMIN sin empleado no confirmó la reserva")

    venta_c_admin = crear_venta(
        c, 3, 301, [{"inventario_id": 3001, "cantidad": 1}]
    )
    require(uno(c, "SELECT empleado_id FROM venta WHERE id=%s",
                (venta_c_admin,)) is None,
            "ADMIN sin empleado no quedó con empleado_id NULL")
    venta_c_reserva = crear_venta(
        c, 3, 301, [{"inventario_id": 3001, "cantidad": 1}],
        reserva_id=6001
    )
    require(uno(c, "SELECT empleado_id FROM venta WHERE id=%s",
                (venta_c_reserva,)) is None,
            "venta desde reserva de ADMIN sin empleado no quedó NULL")

    pagar(c, 3, 301, venta_c_admin)
    pagar(c, 3, 301, venta_c_reserva)
    require((uno(c, "SELECT stock_actual FROM inventario WHERE id=3001"),
             uno(c, "SELECT stock_reservado FROM inventario WHERE id=3001")) == (3, 1),
            "ADMIN sin empleado dejó stock incorrecto")
    require(uno(c, "SELECT estado FROM reserva WHERE id=6001") == "ATENDIDA",
            "ADMIN sin empleado no atendió la reserva")

    venta_c_encargado = crear_venta(
        c, 3, 301, [{"inventario_id": 3001, "cantidad": 1}]
    )
    actor(c, 3, 302)
    try:
        pagar(c, 3, 302, venta_c_encargado)
    except psycopg.Error as exc:
        require(exc.sqlstate == "42501",
                "ENCARGADO sin empleado pagó una venta")
    else:
        raise AssertionError("ENCARGADO sin empleado pagó una venta")
    require(uno(c, "SELECT estado FROM reserva WHERE id=6002") == "PENDIENTE",
            "ENCARGADO sin empleado alteró la reserva 6002")

    # RLS de lectura para personal: cajero de sucursal 1 no ve venta/reserva
    # de sucursal 2, pero sí las de su propia sucursal y el cliente del tenant.
    actor(c, 1, 101)
    venta_branch2 = crear_venta(
        c, 1, 101, [{"inventario_id": 1002, "cantidad": 1}], reserva_id=5003
    )
    actor(c, 1, 103)
    c.execute("SET ROLE fashionstore_api")
    require(uno(c, "SELECT count(*) FROM venta WHERE id=%s", (venta_branch2,)) == 0,
            "RLS permitió al cajero ver venta de otra sucursal")
    require(uno(c, "SELECT count(*) FROM venta WHERE id=%s", (venta_directa,)) == 1,
            "RLS ocultó al cajero su venta de sucursal")
    require(uno(c, "SELECT count(*) FROM reserva WHERE id=5003") == 0,
            "RLS permitió al cajero ver reserva de otra sucursal")
    require(uno(c, "SELECT count(*) FROM reserva WHERE id=5001") == 1,
            "RLS ocultó al cajero una reserva de su sucursal")
    require(uno(c, "SELECT count(*) FROM cliente WHERE id=31") == 1,
            "RLS ocultó al personal el cliente de la empresa")
    c.execute("RESET ROLE")

    print("CU12/CU13 AISLADO PASS: confirmación, venta directa/reserva, "
          "pago, stock, tenant, sucursal, RLS y concurrencia")


def membresias_installer(c):
    return c.execute("""
      SELECT m.roleid::regrole::text AS granted,
             m.member::regrole::text AS member,
             m.admin_option,m.inherit_option,m.set_option,
             pg_get_userbyid(m.grantor) AS grantor
      FROM pg_auth_members m
      WHERE m.member='fs_installer'::regrole
        AND m.roleid IN ('fashionstore_context_owner'::regrole,
                         'fashionstore_sp_owner'::regrole)
      ORDER BY 1,2,3,4,5,6
    """).fetchall()


