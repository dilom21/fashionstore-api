def funciones_actor_dependientes(c) -> None:
    """Se crean después del DDL porque consultan tablas reales."""
    c.execute("""
        CREATE FUNCTION fashionstore_private.actor_es_personal() RETURNS boolean
        LANGUAGE sql STABLE SECURITY DEFINER
        SET search_path=pg_catalog,pg_temp AS $$
          SELECT EXISTS (
            SELECT 1 FROM public.empleado em
            WHERE em.empresa_id=fashionstore_private.actor_empresa_id()
              AND em.usuario_id=fashionstore_private.actor_usuario_id()
              AND em.estado IS TRUE
          )
        $$;
        CREATE FUNCTION fashionstore_private.actor_es_admin() RETURNS boolean
        LANGUAGE sql STABLE SECURITY DEFINER
        SET search_path=pg_catalog,pg_temp AS $$
          SELECT EXISTS (
            SELECT 1 FROM public.usuario_empresa ue
            JOIN public.rol r ON r.id=ue.rol_id AND r.estado IS TRUE
            WHERE ue.empresa_id=fashionstore_private.actor_empresa_id()
              AND ue.usuario_id=fashionstore_private.actor_usuario_id()
              AND ue.estado IS TRUE AND r.nombre='ADMINISTRADOR'
          )
        $$;
        GRANT EXECUTE ON FUNCTION fashionstore_private.actor_es_personal()
          TO fashionstore_sp_owner,fashionstore_api;
        GRANT EXECUTE ON FUNCTION fashionstore_private.actor_es_admin()
          TO fashionstore_sp_owner,fashionstore_api;
    """)


def transferir_ownership_tablas(c) -> None:
    """El instalador de Supabase (postgres) es dueño de las tablas."""
    c.execute("""
      DO $owner$
      DECLARE r record;
      BEGIN
        -- Las secuencias IDENTITY siguen automáticamente al dueño de la tabla.
        FOR r IN
          SELECT c.relname
          FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
          WHERE n.nspname='public' AND c.relkind IN ('r','p')
        LOOP
          EXECUTE format('ALTER TABLE public.%I OWNER TO fs_installer',
                         r.relname);
        END LOOP;
      END $owner$;
    """)


