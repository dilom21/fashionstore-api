def comando(args, *, timeout=90, env=None, capturar=True):
    kwargs = {
        "text": True,
        "timeout": timeout,
        "env": env,
    }
    if capturar:
        kwargs["capture_output"] = True
    else:
        # pg_ctl lanza postgres como proceso hijo: capturar los pipes haría
        # esperar EOF indefinidamente en Windows.
        kwargs["stdout"] = subprocess.DEVNULL
        kwargs["stderr"] = subprocess.DEVNULL
    proceso = subprocess.run([str(x) for x in args], **kwargs)
    if proceso.returncode != 0:
        salida = getattr(proceso, "stdout", None)
        error = getattr(proceso, "stderr", None)
        raise RuntimeError(
            f"Comando falló: {args}\nSTDOUT={salida}\nSTDERR={error}"
        )
    return getattr(proceso, "stdout", "")


