def permisos_y_rls(c):
    # Guard de empresa privado: NOLOGIN no-superuser, dependiente solo
    # de session_user (nunca de variables GUC editables).
    c.execute("""CREATE FUNCTION public.fs_5bg_empresa_actor()
        RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER
        SET search_path=pg_catalog, pg_temp AS $$
          SELECT empresa_id FROM public.fs_5bc_actor
          WHERE principal=session_user::name
        $$""")
    c.execute("REVOKE ALL ON FUNCTION public.fs_5bg_empresa_actor() FROM PUBLIC")
    c.execute(sql.SQL("GRANT CREATE ON SCHEMA public TO {}").format(
        sql.Identifier(VERIFIER)))
    c.execute(sql.SQL("ALTER FUNCTION public.fs_5bg_empresa_actor() OWNER TO {}").format(
        sql.Identifier(VERIFIER)))
    c.execute(sql.SQL("REVOKE CREATE ON SCHEMA public FROM {}").format(
        sql.Identifier(VERIFIER)))
    c.execute(sql.SQL("""GRANT EXECUTE ON FUNCTION public.fs_5bg_empresa_actor()
      TO {}""").format(sql.SQL(",").join(
        sql.Identifier(r) for r in (WRITER,*ROLES))))
    c.execute(sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(
        sql.SQL(",").join(sql.Identifier(r) for r in (WRITER,*ROLES))))
    # RLS escritores por tenant: la empresa siempre se deriva del login
    # real aunque el SP corra como WRITER.
    for table in ALL_TABLES:
        c.execute(sql.SQL("ALTER TABLE public.{} ENABLE ROW LEVEL SECURITY").format(
            sql.Identifier(table)))
        c.execute(sql.SQL("GRANT SELECT ON public.{} TO {}").format(
            sql.Identifier(table),sql.Identifier(WRITER)))
        if table=="empresa":
            predicate="id=public.fs_5bg_empresa_actor()"
        elif table in TENANT_TABLES:
            predicate="empresa_id=public.fs_5bg_empresa_actor()"
        elif table=="usuario":
            predicate="""EXISTS (SELECT 1 FROM public.usuario_empresa ue
                WHERE ue.usuario_id=usuario.id
                  AND ue.empresa_id=public.fs_5bg_empresa_actor())"""
        elif table=="rol":
            predicate="""EXISTS (SELECT 1 FROM public.usuario_empresa ue
                WHERE ue.rol_id=rol.id
                  AND ue.empresa_id=public.fs_5bg_empresa_actor())"""
        elif table=="plan_saas":
            predicate="""EXISTS (SELECT 1 FROM public.suscripcion su
                WHERE su.plan_saas_id=plan_saas.id
                  AND su.empresa_id=public.fs_5bg_empresa_actor())"""
        elif table in ("talla","color"):
            predicate=f"""EXISTS (SELECT 1 FROM public.variante_producto vp
                WHERE vp.{table}_id={table}.id
                  AND vp.empresa_id=public.fs_5bg_empresa_actor())"""
        elif table=="rol_funcion":
            predicate="""EXISTS (SELECT 1 FROM public.usuario_empresa ue
                WHERE ue.rol_id=rol_funcion.rol_id
                  AND ue.empresa_id=public.fs_5bg_empresa_actor())"""
        else:
            foreign="funcion_id" if table=="funcion" else "accion_id"
            predicate=f"""EXISTS (SELECT 1 FROM public.rol_funcion rf
                JOIN public.usuario_empresa ue ON ue.rol_id=rf.rol_id
                WHERE rf.{foreign}={table}.id
                  AND ue.empresa_id=public.fs_5bg_empresa_actor())"""
        c.execute(sql.SQL("""CREATE POLICY {} ON public.{}
            FOR SELECT TO {} USING (""").format(
            sql.Identifier("fs_5bg_"+table+"_select"),
            sql.Identifier(table),sql.Identifier(WRITER))+
            sql.SQL(predicate)+sql.SQL(")"))
        if table in ("inventario","reserva"):
            c.execute(sql.SQL("GRANT SELECT ON public.{} TO {}").format(
                sql.Identifier(table),sql.SQL(",").join(
                    sql.Identifier(r) for r in ROLES)))
            c.execute(sql.SQL("""CREATE POLICY {} ON public.{}
                FOR SELECT TO {} USING (""").format(
                sql.Identifier("fs_5bg_"+table+"_actor"),
                sql.Identifier(table),sql.SQL(",").join(
                    sql.Identifier(r) for r in ROLES))+
                sql.SQL(predicate)+sql.SQL(")"))
    for table in ("usuario_empresa","suscripcion","reserva",
                  "carrito","inventario"):
        # UPDATE columna limitado, como en 5AX.
        cols={
            "usuario_empresa":"estado",
            "suscripcion":"estado",
            "reserva":"estado,observacion",
            "carrito":"estado,fecha_actualizacion",
            "inventario":"stock_reservado,fecha_actualizacion",
        }[table]
        c.execute(sql.SQL("GRANT UPDATE ({}) ON public.{} TO {}").format(
            sql.SQL(cols),sql.Identifier(table),sql.Identifier(WRITER)))
        c.execute(sql.SQL("""CREATE POLICY {} ON public.{}
             FOR UPDATE TO {} USING
             (empresa_id=public.fs_5bg_empresa_actor())
             WITH CHECK (empresa_id=public.fs_5bg_empresa_actor())""").format(
            sql.Identifier("fs_5bg_"+table+"_update"),
            sql.Identifier(table),sql.Identifier(WRITER)))
    for table in ("reserva","detalle_reserva","movimiento_inventario"):
        c.execute(sql.SQL("GRANT INSERT ON public.{} TO {}").format(
            sql.Identifier(table),sql.Identifier(WRITER)))
        c.execute(sql.SQL("""CREATE POLICY {} ON public.{}
             FOR INSERT TO {} WITH CHECK
             (empresa_id=public.fs_5bg_empresa_actor())""").format(
            sql.Identifier("fs_5bg_"+table+"_insert"),
            sql.Identifier(table),sql.Identifier(WRITER)))
        sequence=one(c,"SELECT pg_get_serial_sequence(%s,'id')",
                     (f"public.{table}",))
        require(sequence is not None,
                "secuencia de reserva/detalle/movimiento no existe")
        c.execute(sql.SQL("GRANT USAGE ON SEQUENCE {} TO {}").format(
            sql.Identifier("public",sequence.split(".")[-1].strip('"')),
            sql.Identifier(WRITER)))
    # Los permisos en tablas comerciales son EXCLUSIVAMENTE del NOLOGIN.
    for role in ROLES:
        for table in ("reserva","inventario","carrito",
                      "detalle_reserva","movimiento_inventario"):
            has=one(c,"""SELECT has_table_privilege(%s,%s,'UPDATE')
                  OR has_any_column_privilege(%s,%s,'INSERT')
                  OR has_any_column_privilege(%s,%s,'UPDATE')""",
                 (role,f"public.{table}",role,f"public.{table}",
                  role,f"public.{table}"))
            require(has is False,
                    "5BG BRECHA: actor SQL tiene DML directo "+table)


def instalar_sp_originales(c,fuentes):
    c.execute(sql.SQL("GRANT CREATE ON SCHEMA public TO {}").format(
        sql.Identifier(WRITER)))
    try:
        for proc,(_,signature) in PROCEDURES.items():
            raw=fuentes[proc]
            # Ejecutar CREATE y REVOKE de la FUENTE, en una sola conexión;
            # el SQL completo proviene del repositorio conocido.
            c.execute(raw)
            firma=sql.SQL("public."+proc+"("+signature+")")
            c.execute(sql.SQL("ALTER PROCEDURE {} OWNER TO {}").format(
                firma,sql.Identifier(WRITER)))
            c.execute(sql.SQL("ALTER PROCEDURE {} SECURITY DEFINER").format(firma))
            c.execute(sql.SQL("""ALTER PROCEDURE {}
              SET search_path=pg_catalog, pg_temp""").format(firma))
            c.execute(sql.SQL("GRANT EXECUTE ON PROCEDURE {} TO {}").format(
                firma,sql.SQL(",").join(sql.Identifier(r) for r in ROLES)))
    finally:
        c.execute(sql.SQL("REVOKE CREATE ON SCHEMA public FROM {}").format(
            sql.Identifier(WRITER)))
    for proc in PROCEDURES:
        meta=c.execute("""SELECT p.prosecdef,pg_get_userbyid(p.proowner),
                p.proconfig @> ARRAY['search_path=pg_catalog, pg_temp']::text[]
              FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n
               ON n.oid=p.pronamespace
              WHERE n.nspname='public' AND p.proname=%s AND p.prokind='p'""",
              (proc,)).fetchone()
        # Comprobar directamente proacl y owner, no public como login;
        # el rol PUBLIC no es un principal autenticable.
        require(meta is not None and meta[0] is True
                and meta[1]==WRITER and meta[2] is True,
                "5BG BRECHA: SP sin SECURITY DEFINER NOLOGIN/path: "+proc)
    print("5BG SP REALES PASS: tres FUENTES de borradores CU16–CU18 "
          "montadas con guardia 5AV y owner 5AX NOLOGIN")


