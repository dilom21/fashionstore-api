        path=HERE/"borradores"/file
        raw=path.read_text(encoding="utf-8")
        require(raw.count(f"CREATE OR REPLACE PROCEDURE public.{proc}(")==1,
                "firma/fuente comercial no coincide: "+proc)
        require(raw.count("SECURITY INVOKER")==1,
                "borrador comercial cambió tipo de seguridad")
