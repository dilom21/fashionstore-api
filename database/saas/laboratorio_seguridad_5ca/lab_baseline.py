"""Genera el DDL del baseline histórico a partir del catálogo recuperado.

Fuente: evidence/saas_phase2_20261106/current_catalog/*.json (instantánea real
del esquema de Supabase antes de la migración SaaS). Se reconstruye el esquema
en un clúster desechable porque el respaldo binario no está disponible en este
equipo y las cinco migraciones históricas recuperadas están desactualizadas
(no contienen tablas ni columnas que sí existen en el catálogo).

El resultado es un archivo SQL reproducible: sql/010_baseline_desde_catalogo.sql
"""
from __future__ import annotations

import json
from pathlib import Path

CATALOGO = (Path(__file__).resolve().parents[3] / "evidence"
            / "saas_phase2_20261106" / "current_catalog")
SALIDA = Path(__file__).resolve().parent / "sql" / "010_baseline_desde_catalogo.sql"


def _leer(nombre: str) -> list[dict]:
    return json.loads((CATALOGO / nombre).read_text(encoding="utf-8"))


def _columna(col: dict) -> str:
    tipo = col["type"]
    if tipo.upper() in ("USER-DEFINED", "ARRAY"):
        raise ValueError(f"Tipo no soportado en {col['name']}: {tipo}")
    partes = [f'"{col["name"]}" {tipo}']
    if col.get("identity") == "d":
        partes.append("GENERATED BY DEFAULT AS IDENTITY")
    elif col.get("identity") == "a":
        partes.append("GENERATED ALWAYS AS IDENTITY")
    elif col.get("generated"):
        raise ValueError(f"Columna generada no soportada: {col['name']}")
    if col.get("default") is not None and not col.get("identity"):
        partes.append(f'DEFAULT {col["default"]}')
    if col.get("not_null"):
        partes.append("NOT NULL")
    return " ".join(partes)


def generar() -> tuple[list[str], dict[str, int]]:
    relaciones = [r for r in _leer("relations.json") if r["relkind"] == "r"]
    relaciones.sort(key=lambda r: r["name"])
    restricciones = _leer("constraints.json")
    indices = _leer("indexes.json")
    vistas = _leer("views.json")
    rutinas = _leer("routines.json")
    triggers = _leer("triggers.json")

    sentencias: list[str] = ["SET client_min_messages = warning;"]
    for tabla in relaciones:
        columnas = ",\n  ".join(_columna(c) for c in tabla["columns"])
        sentencias.append(f'CREATE TABLE public."{tabla["name"]}" (\n  {columnas}\n);')

    nombres_restriccion = {c["constraint_name"] for c in restricciones}

    def prioridad(c: dict) -> tuple[int, str]:
        definicion = c["definition"].upper()
        for orden, prefijo in enumerate(("PRIMARY KEY", "UNIQUE", "CHECK",
                                         "FOREIGN KEY", "EXCLUDE")):
            if definicion.startswith(prefijo):
                return (orden, c["constraint_name"])
        return (9, c["constraint_name"])

    # PK y UNIQUE antes que FK: PostgreSQL exige la clave referenciada ya creada.
    for c in sorted(restricciones, key=prioridad):
        definicion = c["definition"]
        if definicion.upper().startswith("NOT NULL"):
            continue
        sentencias.append(
            f'ALTER TABLE ONLY public."{c["table_name"]}" ADD CONSTRAINT '
            f'"{c["constraint_name"]}" {definicion};')

    for i in indices:
        if i["is_primary"] or i["index_name"] in nombres_restriccion:
            continue
        sentencias.append(i["definition"] + ";")

    for r in rutinas:
        if r.get("definition"):
            sentencias.append(r["definition"].rstrip().rstrip(";") + ";")

    for v in vistas:
        opciones = ""
        if v.get("reloptions"):
            opciones = " WITH (" + ", ".join(v["reloptions"]) + ")"
        sentencias.append(
            f'CREATE VIEW public."{v["name"]}"{opciones} AS {v["definition"]}')

    for t in triggers:
        sentencias.append(t["definition"] + ";")

    for tabla in relaciones:
        if tabla.get("rls_enabled"):
            sentencias.append(
                f'ALTER TABLE public."{tabla["name"]}" ENABLE ROW LEVEL SECURITY;')
        if tabla.get("rls_forced"):
            sentencias.append(
                f'ALTER TABLE public."{tabla["name"]}" FORCE ROW LEVEL SECURITY;')

    conteos = {
        "tablas": len(relaciones),
        "restricciones": len(restricciones),
        "indices": len(indices),
        "vistas": len(vistas),
        "rutinas": len(rutinas),
        "triggers": len(triggers),
    }
    return sentencias, conteos


def main() -> int:
    sentencias, conteos = generar()
    SALIDA.parent.mkdir(parents=True, exist_ok=True)
    cabecera = (
        "-- GENERADO por lab_baseline.py a partir de current_catalog/*.json.\n"
        "-- Reconstrucción del esquema histórico para el laboratorio 5CA.\n"
        "-- Sólo se ejecuta en un clúster desechable, nunca en Supabase.\n"
    )
    SALIDA.write_text(cabecera + "\n".join(sentencias) + "\n", encoding="utf-8")
    print("sentencias:", len(sentencias), "| objetos:", conteos)
    print("archivo:", SALIDA)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
