-- LABORATORIO 5CA — sustituto LOCAL de Supabase Vault. NO ES EQUIVALENTE.
-- Supabase Vault cifra los secretos y expone vault.decrypted_secrets sólo a
-- roles autorizados. Aquí se imita la MISMA INTERFAZ de lectura para que
-- 050a se ejecute sin cambios, pero:
--   * el secreto se guarda en texto claro en una tabla local desechable;
--   * no hay cifrado, ni KMS, ni auditoría de Vault;
--   * no se prueba la integración real con Supabase.
-- Por tanto este archivo NO se promociona a Supabase.
CREATE SCHEMA IF NOT EXISTS vault;
CREATE TABLE IF NOT EXISTS vault.secrets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    secret text NOT NULL,
    description text,
    created_at timestamptz NOT NULL DEFAULT now()
);
REVOKE ALL ON vault.secrets FROM PUBLIC;
-- HALLAZGO 5CA: la vista NO puede ser security_invoker. Con security_invoker=true
-- el owner NOLOGIN de actor_claims() necesita SELECT directo sobre vault.secrets
-- y la verificación JWT falla con "permission denied for table secrets".
-- En Supabase vault.decrypted_secrets es una vista con derechos del propietario,
-- así que se reproduce ese comportamiento aquí.
CREATE OR REPLACE VIEW vault.decrypted_secrets AS
SELECT s.id, s.name, s.secret AS decrypted_secret, s.description, s.created_at
FROM vault.secrets s;
REVOKE ALL ON vault.decrypted_secrets FROM PUBLIC;

-- pgcrypto vive en el esquema extensions, igual que en Supabase.
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

DO $check$
BEGIN
    IF to_regprocedure('extensions.hmac(bytea,bytea,text)') IS NULL THEN
        RAISE EXCEPTION 'pgcrypto.hmac no disponible en extensions';
    END IF;
    IF to_regclass('vault.decrypted_secrets') IS NULL THEN
        RAISE EXCEPTION 'vault.decrypted_secrets no disponible';
    END IF;
END $check$;
