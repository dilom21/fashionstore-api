BEGIN;

-- 1. Cada EMPRESA representa un tenant; una sucursal NO es un tenant.
CREATE TABLE public.empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(180) NOT NULL,
    nombre_comercial VARCHAR(150) NOT NULL,
    slug VARCHAR(80) NOT NULL,
    nit VARCHAR(40),
    correo_contacto VARCHAR(150),
    telefono VARCHAR(35),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_empresa_slug UNIQUE (slug),
    CONSTRAINT ck_empresa_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_empresa_razon_social CHECK (LENGTH(BTRIM(razon_social)) > 0),
    CONSTRAINT ck_empresa_nombre_comercial CHECK (LENGTH(BTRIM(nombre_comercial)) > 0)
);
COMMENT ON TABLE public.empresa IS 'Tenant contratante. Varias sucursales podran pertenecer a la misma empresa.';

-- 2. Limites y capacidades configurables en BD, consumidos por FastAPI.
-- BASICO: 2 sucursales; PROFESIONAL: 10 sucursales y reportes generativos IA.
-- Los valores concretos de los planes se insertaran en el paso 4.
CREATE TABLE public.plan_saas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(35) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    max_sucursales_activas INTEGER NOT NULL,
    permite_productos BOOLEAN NOT NULL DEFAULT TRUE,
    permite_ventas BOOLEAN NOT NULL DEFAULT TRUE,
    permite_reservas BOOLEAN NOT NULL DEFAULT TRUE,
    permite_offline BOOLEAN NOT NULL DEFAULT TRUE,
    permite_reportes_convencionales BOOLEAN NOT NULL DEFAULT TRUE,
    permite_reportes_ia BOOLEAN NOT NULL DEFAULT FALSE,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_plan_saas_codigo UNIQUE (codigo),
    CONSTRAINT ck_plan_saas_codigo CHECK (codigo ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT ck_plan_saas_sucursales CHECK (max_sucursales_activas BETWEEN 1 AND 1000)
);
COMMENT ON TABLE public.plan_saas IS 'Catalogo de planes SaaS; FastAPI debe aplicar las capacidades y limites almacenados.';

-- 3. Historial de suscripciones: cada empresa puede renovar o cambiar de plan.
-- A lo sumo una suscripcion marcada ACTIVA por empresa.
CREATE TABLE public.suscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    plan_saas_id BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    observacion TEXT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_suscripcion_empresa FOREIGN KEY (empresa_id)
        REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_suscripcion_plan FOREIGN KEY (plan_saas_id)
        REFERENCES public.plan_saas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_suscripcion_fecha CHECK (fecha_vencimiento >= fecha_inicio),
    CONSTRAINT ck_suscripcion_estado CHECK
        (estado IN ('PENDIENTE', 'ACTIVA', 'SUSPENDIDA', 'VENCIDA', 'CANCELADA'))
);
CREATE UNIQUE INDEX uq_suscripcion_empresa_activa
    ON public.suscripcion(empresa_id) WHERE estado = 'ACTIVA';
CREATE INDEX idx_suscripcion_empresa_vencimiento
    ON public.suscripcion(empresa_id, fecha_vencimiento DESC);
COMMENT ON TABLE public.suscripcion IS 'Contratacion y vigencia de plan por tenant; el servidor valida la vigencia real.';

-- 4. Un usuario global puede pertenecer a distintas empresas con roles distintos.
-- El rol global en usuario.rol_id queda SIN CAMBIOS en esta etapa.
-- FastAPI debera utilizar usuario_empresa.rol_id en el contexto del tenant.
CREATE TABLE public.usuario_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    empresa_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_usuario_empresa_usuario FOREIGN KEY (usuario_id)
        REFERENCES public.usuario(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_usuario_empresa_empresa FOREIGN KEY (empresa_id)
        REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_usuario_empresa_rol FOREIGN KEY (rol_id)
        REFERENCES public.rol(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_usuario_empresa UNIQUE (usuario_id, empresa_id)
);
CREATE INDEX idx_usuario_empresa_empresa_rol
    ON public.usuario_empresa(empresa_id, rol_id) WHERE estado = TRUE;
COMMENT ON TABLE public.usuario_empresa IS 'Membresia y rol por tenant; autenticar usuario no concede acceso a todas las empresas.';

-- 5. Identidad visual y ajustes propios de cada empresa.
CREATE TABLE public.empresa_configuracion (
    empresa_id BIGINT PRIMARY KEY,
    logo_url TEXT,
    color_primario VARCHAR(7) NOT NULL DEFAULT '#111827',
    color_secundario VARCHAR(7) NOT NULL DEFAULT '#FFFFFF',
    moneda VARCHAR(3) NOT NULL DEFAULT 'BOB',
    zona_horaria VARCHAR(80) NOT NULL DEFAULT 'America/La_Paz',
    configuracion_extra JSONB NOT NULL DEFAULT '{}'::JSONB,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_empresa_configuracion_empresa FOREIGN KEY (empresa_id)
        REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_empresa_configuracion_primario CHECK (color_primario ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_empresa_configuracion_secundario CHECK (color_secundario ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_empresa_configuracion_extra CHECK (jsonb_typeof(configuracion_extra) = 'object')
);
COMMENT ON TABLE public.empresa_configuracion IS 'Configuracion visual y operativa propia de cada tenant.';

