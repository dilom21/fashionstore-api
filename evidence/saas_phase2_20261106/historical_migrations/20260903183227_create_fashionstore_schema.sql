    c.nombre AS color,
    i.temporada_id,
    te.nombre AS temporada,
    i.stock_actual,
    i.stock_reservado,
    (i.stock_actual - i.stock_reservado) AS stock_disponible,
    i.fecha_actualizacion
FROM inventario i
INNER JOIN sucursal s ON s.id = i.sucursal_id
INNER JOIN variante_producto vp ON vp.id = i.variante_producto_id
INNER JOIN producto p ON p.id = vp.producto_id
INNER JOIN talla t ON t.id = vp.talla_id
INNER JOIN color c ON c.id = vp.color_id
INNER JOIN temporada te ON te.id = i.temporada_id;

