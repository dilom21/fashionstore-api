-- T02/T04: idempotencia durable para mutaciones del cliente autenticado.
-- No almacena secretos ni datos de tarjeta. empresa_id y usuario_id proceden
-- del contexto JWT validado; RLS fuerza la empresa de la asercion SaaS.
BEGIN;

CREATE TABLE IF NOT EXISTS public.operacion_cliente_idempotente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id BIGINT NOT NULL REFERENCES public.empresa(id),
  usuario_id BIGINT NOT NULL REFERENCES public.usuario(id),
  tipo VARCHAR(40) NOT NULL,
  operacion_id VARCHAR(36) NOT NULL,
  huella VARCHAR(64) NOT NULL,
  estado VARCHAR(20) NOT NULL,
  recurso_id BIGINT,
  respuesta_json TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_operacion_cliente_tipo CHECK (tipo IN ('VENTA_DIGITAL')),
  CONSTRAINT ck_operacion_cliente_estado CHECK (estado IN ('EN_PROCESO','PROCESADA')),
  CONSTRAINT ck_operacion_cliente_huella CHECK (huella ~ '^[0-9a-f]{64}$'),
  CONSTRAINT uq_operacion_cliente_idempotente
    UNIQUE (empresa_id, usuario_id, tipo, operacion_id)
);

CREATE INDEX IF NOT EXISTS ix_operacion_cliente_empresa_creado
  ON public.operacion_cliente_idempotente (empresa_id, creado_en DESC);

ALTER TABLE public.operacion_cliente_idempotente ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.operacion_cliente_idempotente FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_operacion_cliente ON public.operacion_cliente_idempotente;
CREATE POLICY tenant_operacion_cliente ON public.operacion_cliente_idempotente
  USING (empresa_id = saas.tenant_actual())
  WITH CHECK (empresa_id = saas.tenant_actual());

DO $seguridad$
DECLARE v_runtime name := current_setting('saas.runtime_role', true);
BEGIN
  IF v_runtime IS NULL OR btrim(v_runtime) = '' THEN
    v_runtime := 'fashionstore_app';
  END IF;
  EXECUTE format(
    'REVOKE ALL ON public.operacion_cliente_idempotente FROM PUBLIC; '
    'GRANT SELECT, INSERT, UPDATE ON public.operacion_cliente_idempotente TO %I',
    v_runtime
  );
  EXECUTE format(
    'GRANT USAGE, SELECT ON SEQUENCE public.operacion_cliente_idempotente_id_seq TO %I',
    v_runtime
  );
END $seguridad$;

COMMIT;
