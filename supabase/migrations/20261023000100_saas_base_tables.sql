-- REVISAR ANTES DE EJECUTAR. En este paso SOLO se crea el archivo.
-- Fuente: Examen Parcial-2 - Sistemas 2 - S2-2026,
-- Desafio VI, apartados 9.1 a 9.6 (PostgreSQL compartido y planes).
--
-- Dependencias: esquema public con usuario(id BIGINT), rol(id BIGINT).
-- No inserta tenants, planes ni membresias; no modifica tablas antiguas.
-- No garantiza por si sola aislamiento de las operaciones anteriores.
-- IMPORTANTE: ejecutar una sola vez y solo tras probar en base local.
-- Nota: el nombre de esta migracion sigue la convencion Supabase CLI.
BEGIN;

SET LOCAL lock_timeout = '5s';

-- Guardas: detectar una BD incorrecta o una migracion ya aplicada.
DO $preflight$
BEGIN
  IF to_regclass('public.usuario') IS NULL
     OR to_regclass('public.rol') IS NULL THEN
    RAISE EXCEPTION
      'Base incompatible: faltan public.usuario y/o public.rol';
  END IF;
  IF to_regclass('public.empresa') IS NOT NULL
     OR to_regclass('public.plan_saas') IS NOT NULL
     OR to_regclass('public.suscripcion') IS NOT NULL
     OR to_regclass('public.usuario_empresa') IS NOT NULL
     OR to_regclass('public.empresa_configuracion') IS NOT NULL THEN
    RAISE EXCEPTION
      'Una o mas tablas SaaS ya existen: revisar migraciones; no reejecutar';
  END IF;
END;
$preflight$;

-- 1) Tenant / empresa independiente.
CREATE TABLE public.empresa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  razon_social VARCHAR(180) NOT NULL,
  nombre_comercial VARCHAR(150) NOT NULL,
  slug VARCHAR(80) NOT NULL,
  nit VARCHAR(40),
  correo_contacto VARCHAR(150),
  telefono VARCHAR(35),
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_empresa_slug UNIQUE (slug),
  CONSTRAINT ck_empresa_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  CONSTRAINT ck_empresa_razon_social CHECK (LENGTH(BTRIM(razon_social)) > 0),
  CONSTRAINT ck_empresa_nombre_comercial CHECK (LENGTH(BTRIM(nombre_comercial)) > 0)
);
COMMENT ON TABLE public.empresa IS
  'Empresa contratante = tenant. Una empresa puede tener varias sucursales.';

-- 2) Planes configurables. Los valores BASICO y PROFESIONAL se sembraran
-- en un paso posterior: 2 vs 10 sucursales activas, IA solo PROFESIONAL.
CREATE TABLE public.plan_saas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(35) NOT NULL,
  nombre VARCHAR(100) NOT NULL,
  descripcion TEXT,
  max_sucursales_activas INTEGER NOT NULL,
  permite_productos BOOLEAN NOT NULL DEFAULT TRUE,
  permite_ventas BOOLEAN NOT NULL DEFAULT TRUE,
  permite_reservas BOOLEAN NOT NULL DEFAULT TRUE,
  permite_offline BOOLEAN NOT NULL DEFAULT TRUE,
  permite_reportes_convencionales BOOLEAN NOT NULL DEFAULT TRUE,
  permite_reportes_ia BOOLEAN NOT NULL DEFAULT FALSE,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_plan_saas_codigo UNIQUE (codigo),
  CONSTRAINT ck_plan_saas_codigo CHECK (codigo ~ '^[A-Z][A-Z0-9_]*$'),
  CONSTRAINT ck_plan_saas_sucursales CHECK (
    max_sucursales_activas BETWEEN 1 AND 1000
  )
);
COMMENT ON TABLE public.plan_saas IS
  'Planes SaaS y capacidades; limite de sucursales se valida en backend.';

-- 3) Historial de suscripciones; solo una marcada ACTIVA por empresa.
CREATE TABLE public.suscripcion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id BIGINT NOT NULL,
  plan_saas_id BIGINT NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
  observacion TEXT,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_suscripcion_empresa FOREIGN KEY (empresa_id)
    REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_suscripcion_plan FOREIGN KEY (plan_saas_id)
    REFERENCES public.plan_saas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT ck_suscripcion_fecha CHECK (fecha_vencimiento >= fecha_inicio),
  CONSTRAINT ck_suscripcion_estado CHECK (
    estado IN ('PENDIENTE', 'ACTIVA', 'SUSPENDIDA', 'VENCIDA', 'CANCELADA')
  )
);
CREATE UNIQUE INDEX uq_suscripcion_empresa_activa
  ON public.suscripcion(empresa_id) WHERE estado = 'ACTIVA';
CREATE INDEX idx_suscripcion_empresa_vencimiento
  ON public.suscripcion(empresa_id, fecha_vencimiento DESC);
COMMENT ON TABLE public.suscripcion IS
  'Suscripcion por tenant; verificar estado y vigencia efectiva en FastAPI.';

-- 4) Identidad global con roles diferenciados POR empresa.
-- El rol global usuario.rol_id se conserva para migracion gradual;
-- NO concede acceso multitenant por si mismo.
CREATE TABLE public.usuario_empresa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL,
  empresa_id BIGINT NOT NULL,
  rol_id BIGINT NOT NULL,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_usuario_empresa_usuario FOREIGN KEY (usuario_id)
    REFERENCES public.usuario(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_usuario_empresa_empresa FOREIGN KEY (empresa_id)
    REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_usuario_empresa_rol FOREIGN KEY (rol_id)
    REFERENCES public.rol(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT uq_usuario_empresa UNIQUE (usuario_id, empresa_id)
);
CREATE INDEX idx_usuario_empresa_empresa_rol
  ON public.usuario_empresa(empresa_id, rol_id) WHERE estado IS TRUE;
COMMENT ON TABLE public.usuario_empresa IS
  'Membresia y rol por empresa; la autorizacion se valida en el backend.';

-- 5) Configuracion operativa / visual propia del tenant.
CREATE TABLE public.empresa_configuracion (
  empresa_id BIGINT PRIMARY KEY,
  logo_url TEXT,
  color_primario VARCHAR(7) NOT NULL DEFAULT '#111827',
  color_secundario VARCHAR(7) NOT NULL DEFAULT '#FFFFFF',
  moneda VARCHAR(3) NOT NULL DEFAULT 'BOB',
  zona_horaria VARCHAR(80) NOT NULL DEFAULT 'America/La_Paz',
  configuracion_extra JSONB NOT NULL DEFAULT '{}'::JSONB,
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_empresa_configuracion_empresa FOREIGN KEY (empresa_id)
    REFERENCES public.empresa(id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT ck_empresa_configuracion_primario CHECK (
    color_primario ~ '^#[0-9A-Fa-f]{6}$'
  ),
  CONSTRAINT ck_empresa_configuracion_secundario CHECK (
    color_secundario ~ '^#[0-9A-Fa-f]{6}$'
  ),
  CONSTRAINT ck_empresa_configuracion_extra CHECK (
    jsonb_typeof(configuracion_extra) = 'object'
  )
);
COMMENT ON TABLE public.empresa_configuracion IS
  'Configuraciones visuales y operativas aisladas por tenant.';

-- Las tablas en public pueden estar expuestas por Data API de Supabase.
-- RLS sin politicas es deny-by-default para roles SUJETOS a RLS.
-- Los roles BYPASSRLS (p.ej. postgres y service_role) NO son protegidos
-- por estas politicas: auditar las credenciales del backend en otro paso.
ALTER TABLE public.empresa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.plan_saas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.suscripcion ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuario_empresa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.empresa_configuracion ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.empresa, public.plan_saas,
  public.suscripcion, public.usuario_empresa, public.empresa_configuracion
FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.empresa_id_seq, public.plan_saas_id_seq,
  public.suscripcion_id_seq, public.usuario_empresa_id_seq
FROM PUBLIC;

-- Supabase tiene anon/authenticated; PostgreSQL local restaurado puede NO
-- tenerlos. Revocarlos solo si existen (sin crear roles globales artificiales).
DO $safe_roles$
DECLARE
  nombre_rol TEXT;
BEGIN
  FOREACH nombre_rol IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = nombre_rol) THEN
      EXECUTE format(
        'REVOKE ALL ON TABLE public.empresa, public.plan_saas, public.suscripcion, public.usuario_empresa, public.empresa_configuracion FROM %I',
        nombre_rol
      );
      EXECUTE format(
        'REVOKE ALL ON SEQUENCE public.empresa_id_seq, public.plan_saas_id_seq, public.suscripcion_id_seq, public.usuario_empresa_id_seq FROM %I',
        nombre_rol
      );
    END IF;
  END LOOP;
END;
$safe_roles$;

COMMIT;

